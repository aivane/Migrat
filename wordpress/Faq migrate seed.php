function fund_faq_question_exists($question) {
    $query = new WP_Query([
        'post_type'      => 'faq',
        'post_status'    => 'any',
        'title'          => $question,
        'posts_per_page' => 1,
        'fields'         => 'ids',
        'no_found_rows'  => true,
    ]);

    return $query->have_posts();
}