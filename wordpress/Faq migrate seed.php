            'การจัดอันดับมักอ้างอิงจากผลการดำเนินงานย้อนหลัง ความสม่ำเสมอ และระดับความเสี่ยง ซึ่งเป็นข้อมูลเชิงสถิติ ไม่สามารถรับประกันผลในอนาคต ผู้ใช้งานควรพิจารณาร่วมกับนโยบายการลงทุน ระยะเวลา และเป้าหมายส่วนบุคคล'],
